import math

W, H = 2560.0, 1440.0
LAT_TOP, LAT_BOT = 80.0, -58.0

def merc(lat):
    return math.asinh(math.tan(math.radians(lat)))

M_TOP, M_BOT = merc(LAT_TOP), merc(LAT_BOT)
RY = H / (M_TOP - M_BOT)

def project(lon, lat):
    x = (lon + 180.0) / 360.0 * W
    y = (M_TOP - merc(lat)) * RY
    return (x, y)

def catmull_path(pts_ll, closed=True, tension=1.0):
    """Convierte polilinea lon/lat en path SVG cubico via Catmull-Rom."""
    P = [project(lon, lat) for lon, lat in pts_ll]
    n = len(P)
    if n < 3:
        return ""
    d = [f"M {P[0][0]:.1f} {P[0][1]:.1f}"]
    rng = range(n) if closed else range(n - 1)
    for i in rng:
        p0 = P[(i - 1) % n] if closed else P[max(i - 1, 0)]
        p1 = P[i]
        p2 = P[(i + 1) % n] if closed else P[min(i + 1, n - 1)]
        p3 = P[(i + 2) % n] if closed else P[min(i + 2, n - 1)]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6.0 * tension,
              p1[1] + (p2[1] - p0[1]) / 6.0 * tension)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6.0 * tension,
              p2[1] - (p3[1] - p1[1]) / 6.0 * tension)
        d.append(f"C {c1[0]:.1f} {c1[1]:.1f}, {c2[0]:.1f} {c2[1]:.1f}, {p2[0]:.1f} {p2[1]:.1f}")
    if closed:
        d.append("Z")
    return " ".join(d)

